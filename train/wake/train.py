"""Train the "Hey Bol OS" wake-word model from scratch and export it for the numpy runtime.

    uv run python train/wake/corpus.py          # once, after generate.py
    uv run python train/wake/train.py            # ~1 h on a laptop CPU; writes train/wake/work/wake_candidate.npz
    uv run python train/wake/train.py --resume   # continue after an interruption (work/train_state.pt)
    uv run python train/wake/evaluate.py --install

Model: per-bin normalised log-mel (160 frames x 40) -> six 1D convolutions over time (batch norm, ReLU;
strides 2/1/2/1/1/1, dilations 1/2/1/2/4/8, receptive field 1.29 s) -> mean and max over time -> 64 -> 1
logit. ~175k parameters, ~4.7 M multiply-adds per evaluation (12.5 evaluations per second).

Every epoch is freshly generated by worker processes (augment.corrupt on random windows, see windows.py), so
the model never sees the same augmented window twice. Hard negatives: each epoch the negatives the current
model scores highest are kept in a bank and replayed. Feature-level SpecAugment (one frequency and one time
mask) on top. Checkpoint selection uses the val voices only, scored the way the app runs: long val streams
(phrases in clean/noisy/context conditions, near misses, ordinary speech, noise) are cut into the windows the
runtime evaluates, and the epoch with the best recall at no more than 0.3 false accepts/hour is kept.
"""

import argparse
import json
import multiprocessing as mp
import os
import sys
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = Path(__file__).resolve().parents[2]
if not __package__:  # run as a script: drop this folder from the path so train/wake/train.py cannot shadow the
    # "train" package, and import the siblings as train.wake.*
    sys.path[:] = [p for p in sys.path if Path(p or ".").resolve() != ROOT / "train" / "wake"]
    sys.path.insert(0, str(ROOT))

WORK = HERE / "work"
# (in, out, kernel, stride, dilation)
# The last two dilated layers widen the receptive field to 129 frames (1.29 s), so one unit hears the whole
# phrase in order ("hey" before "bol" before "OS"), not a bag of 0.4 s pieces.
CONVS = [(40, 64, 5, 2, 1), (64, 64, 3, 1, 2), (64, 96, 3, 2, 1), (96, 96, 3, 1, 2), (96, 128, 3, 1, 4),
         (128, 128, 3, 1, 8)]
MIX = {"pos": 0.30, "partial": 0.08, "post": 0.05, "near": 0.17, "speech": 0.30, "noise": 0.10}

_sampler = None


def _init_worker(split: str) -> None:
    global _sampler
    os.environ.setdefault("OMP_NUM_THREADS", "1")
    from train.wake.windows import Sampler

    _sampler = Sampler(split)


def _make(job: tuple[int, int, str, float]) -> tuple[np.ndarray, np.ndarray]:
    seed, n, kinds, strength = job
    rng = np.random.default_rng(seed)
    names = list(MIX) if kinds == "mix" else [kinds]
    p = np.array([MIX[k] for k in names]) / sum(MIX[k] for k in names)
    xs, ys = [], []
    for kind in rng.choice(names, size=n, p=p):
        x, y = _sampler.window(str(kind), rng, strength)
        xs.append(x)
        ys.append(y)
    # float16 halves the memory of an epoch (log-mel values are in about -14..12, so 3 decimals survive).
    return np.stack(xs).astype(np.float16), np.array(ys, np.float32)


def generate(pool, seed: int, count: int, kinds: str = "mix", strength: float = 1.0, chunk: int = 64):
    jobs = [(seed * 100003 + i, min(chunk, count - i * chunk), kinds, strength)
            for i in range((count + chunk - 1) // chunk)]
    parts = pool.map(_make, jobs)
    return np.concatenate([p[0] for p in parts]), np.concatenate([p[1] for p in parts])


def build_model(torch, nn):
    class WakeCNN(nn.Module):
        def __init__(self):
            super().__init__()
            layers = []
            for cin, cout, k, s, d in CONVS:
                layers += [nn.Conv1d(cin, cout, k, stride=s, dilation=d, bias=False), nn.BatchNorm1d(cout), nn.ReLU()]
            self.body = nn.Sequential(*layers)
            self.fc0 = nn.Linear(2 * CONVS[-1][1], 64)
            self.drop = nn.Dropout(0.1)
            self.fc1 = nn.Linear(64, 1)

        def forward(self, x):  # x: (B, T, F) normalised
            h = self.body(x.transpose(1, 2))
            h = torch.cat([h.mean(dim=2), h.amax(dim=2)], dim=1)
            return self.fc1(self.drop(torch.relu(self.fc0(h)))).squeeze(1)

    return WakeCNN()


def export(model, mean: np.ndarray, std: np.ndarray, path: Path, meta: dict) -> None:
    """Fold batch norm into the convolutions and save the arrays bolos.wake.WakeNet reads."""
    arrays = {"norm_mean": mean.astype(np.float32), "norm_std": std.astype(np.float32)}
    mods = list(model.body)
    for i in range(len(CONVS)):
        conv, bn = mods[3 * i], mods[3 * i + 1]
        scale = (bn.weight / (bn.running_var + bn.eps).sqrt()).detach().numpy()
        arrays[f"conv{i}.w"] = (conv.weight.detach().numpy() * scale[:, None, None]).astype(np.float32)
        arrays[f"conv{i}.b"] = (bn.bias.detach().numpy() - bn.running_mean.detach().numpy() * scale).astype(np.float32)
        arrays[f"conv{i}.sd"] = np.array([CONVS[i][3], CONVS[i][4]], np.int32)
    for j, fc in enumerate([model.fc0, model.fc1]):
        arrays[f"fc{j}.w"] = fc.weight.detach().numpy().astype(np.float32)
        arrays[f"fc{j}.b"] = fc.bias.detach().numpy().astype(np.float32)
    arrays["meta"] = np.array(json.dumps(meta))
    np.savez(path, **arrays)


def spec_augment(x: np.ndarray, rng: np.random.Generator, fill: np.ndarray) -> np.ndarray:
    """One frequency mask (<= 6 bins) and one time mask (<= 12 frames) per window, on half the batch. Masked
    cells get the per-bin training mean (0 after normalisation), not an arbitrary loud value."""
    b, t, f = x.shape
    for i in np.where(rng.random(b) < 0.5)[0]:
        f0, fw = rng.integers(0, f), rng.integers(1, 7)
        x[i, :, f0:f0 + fw] = fill[f0:f0 + fw]
        t0, tw = rng.integers(0, t - 20), rng.integers(1, 13)
        x[i, t0:t0 + tw, :] = fill
    return x


class StreamVal:
    """The val voices as long streams (evaluate.positive_stream / negative_stream), cut into exactly the windows
    the runtime scores (every 8 frames, ring buffer starting at the silence floor). Scoring them with the torch
    model each epoch selects the checkpoint by the deployment metric: recall at a false-accept budget."""

    def __init__(self, split: str = "val", seed: int = 7, passes: int = 1):
        from bolos.wake import LOG_FLOOR, N_MELS, log_mel
        from train.wake import evaluate

        self.evaluate = evaluate
        self.window, self.every = 160, 8

        def windows(audio: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
            pcm = np.clip(audio * 32768, -32768, 32767).astype(np.int16)
            feats = log_mel(pcm)
            padded = np.concatenate([np.full((self.window, N_MELS), np.log(LOG_FLOOR), np.float32), feats])
            return padded, np.arange(self.every, len(feats) + 1, self.every)

        audio, self.ends = evaluate.positive_stream(split, seed)
        self.pos = windows(audio)
        self.neg, self.hours = [], 0.0
        for p in range(passes):
            audio, h = evaluate.negative_stream(split, seed + 100 + p)
            self.neg.append(windows(audio))
            self.hours += h

    def score(self, predict) -> tuple[float, dict]:
        """(selection score, val metrics at the threshold chosen on these streams)."""
        def run(padded, n):
            view = np.lib.stride_tricks.sliding_window_view(padded, self.window, axis=0)  # (T, 40, 160)
            scores = np.concatenate([predict(view[n[i:i + 1024]].transpose(0, 2, 1))
                                     for i in range(0, len(n), 1024)])
            return (n - 1) * 160 + 400, scores

        pt, ps = run(*self.pos)
        ev = {"pos": (pt, ps, self.ends), "neg": [run(*w) for w in self.neg], "hours": self.hours,
              "refractory": int(1.5 * 16000)}
        thr, _ = self.evaluate.choose_threshold(ev, 0.3)
        m = self.evaluate.metrics(ev, thr)
        loose = self.evaluate.metrics(ev, self.evaluate.choose_threshold(ev, 5.0)[0])["recall"]
        # Recall with (almost) no false accepts first; recall at a looser budget breaks ties and smooths it.
        return m["recall"] + 0.1 * loose, {"threshold": thr, "recall": m["recall"], "recall@5fa": loose,
                                           "fa_per_hour": m["fa_per_hour"]}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--epochs", type=int, default=40)
    ap.add_argument("--per-epoch", type=int, default=16000)
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--threads", type=int, default=4)
    ap.add_argument("--lr", type=float, default=2e-3)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", type=Path, default=WORK / "wake_candidate.npz")
    ap.add_argument("--state", type=Path, default=WORK / "train_state.pt", help="checkpoint saved every epoch")
    ap.add_argument("--resume", action="store_true", help="continue from --state")
    args = ap.parse_args()

    import torch
    from torch import nn

    torch.manual_seed(args.seed)
    torch.set_num_threads(args.threads)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    rng = np.random.default_rng(args.seed)
    ctx = mp.get_context("spawn")
    WORK.mkdir(exist_ok=True)

    t0 = time.time()
    val = StreamVal()
    print(f"val streams: {len(val.ends)} phrases, {val.hours:.2f} h of negatives ({time.time() - t0:.0f} s)",
          flush=True)

    pool = ctx.Pool(args.workers, initializer=_init_worker, initargs=("train",))
    state = torch.load(args.state, weights_only=False) if args.resume and args.state.exists() else None
    if state:
        mean, std = state["mean"], state["std"]
    else:
        x0 = generate(pool, 1, 4000)[0].astype(np.float32)
        mean, std = x0.mean(axis=(0, 1)), x0.std(axis=(0, 1)) + 1e-3
        del x0

    def norm(x):
        return torch.from_numpy((x.astype(np.float32) - mean) / std)

    def predict(x, batch: int = 512) -> np.ndarray:
        with torch.no_grad():
            return np.concatenate([torch.sigmoid(model(norm(x[i:i + batch]).to(device))).cpu().numpy()
                                   for i in range(0, len(x), batch)])

    model = build_model(torch, nn).to(device)
    print(f"parameters: {sum(p.numel() for p in model.parameters())}, device {device}", flush=True)
    opt = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=1e-3)
    steps_per_epoch = args.per_epoch // 256 + 12  # + the replayed hard-negative bank
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=args.lr, total_steps=args.epochs * steps_per_epoch + 10,
                                                pct_start=0.1)
    bank_x = np.zeros((0, 160, 40), np.float16)
    best, history, start = -1.0, [], 0
    if state:
        model.load_state_dict(state["model"])
        opt.load_state_dict(state["opt"])
        sched.load_state_dict(state["sched"])
        rng.bit_generator.state = state["rng"]
        bank_x, best, history, start = state["bank"], state["best"], state["history"], state["epoch"] + 1
        print(f"resumed after epoch {state['epoch']} (best {best:.3f})", flush=True)

    def epoch_jobs(epoch: int) -> list:
        base = 10_000 + (epoch + 2) * 100003
        return [(base + i, 64, "mix", 1.0) for i in range(args.per_epoch // 64)]

    pending = pool.map_async(_make, epoch_jobs(start)) if start < args.epochs else None
    for epoch in range(start, args.epochs):
        t0 = time.time()
        parts = pending.get()
        x = np.concatenate([p[0] for p in parts])
        y = np.concatenate([p[1] for p in parts])
        del parts
        if epoch + 1 < args.epochs:  # generate the next epoch while this one trains
            pending = pool.map_async(_make, epoch_jobs(epoch + 1))
        gen_wait = time.time() - t0
        # Hard negatives: replay the bank (scored by the model as it was last epoch).
        if len(bank_x):
            x = np.concatenate([x, bank_x])
            y = np.concatenate([y, np.zeros(len(bank_x), np.float32)])
        model.train()
        order = rng.permutation(len(y))
        total, steps = 0.0, len(y) // 256
        for s in range(steps):
            idx = order[s * 256:(s + 1) * 256]
            xb = norm(spec_augment(x[idx].astype(np.float32), rng, mean)).to(device)
            yb = torch.from_numpy(y[idx]).to(device)
            logits = model(xb)
            target = yb * 0.97 + 0.01
            weight = 1.0 + yb * 1.0
            loss = (nn.functional.binary_cross_entropy_with_logits(logits, target, reduction="none") * weight).mean()
            opt.zero_grad()
            loss.backward()
            opt.step()
            if sched.last_epoch + 1 < sched.total_steps:
                sched.step()
            total += loss.item()
        model.eval()
        neg = np.where(y == 0)[0]
        scores = predict(x[neg])
        top = np.argsort(-scores)[:3000]
        bank_x = x[neg[top[scores[top] > 0.05]]].copy()
        del x, y
        sel, vm = val.score(predict)
        history.append({"epoch": epoch, "loss": total / max(1, steps), "bank": len(bank_x), "select": sel, **vm})
        print(f"epoch {epoch:2d} loss {total / max(1, steps):.4f} val stream: recall {vm['recall']:.3f} at thr "
              f"{vm['threshold']:.2f} (FA/h {vm['fa_per_hour']:.2f}), recall@5FA/h {vm['recall@5fa']:.3f} "
              f"bank {len(bank_x)} ({time.time() - t0:.0f} s, waited {gen_wait:.0f} s for data)", flush=True)
        if sel >= best:
            best = sel
            export(model.cpu(), mean, std, args.out, {"threshold": vm["threshold"], "window": 160, "every": 8,
                                                      "refractory": 1.5, "epoch": epoch, "convs": CONVS})
            model.to(device)
        torch.save({"model": model.state_dict(), "opt": opt.state_dict(), "sched": sched.state_dict(),
                    "rng": rng.bit_generator.state, "bank": bank_x, "best": best, "history": history,
                    "epoch": epoch, "mean": mean, "std": std}, args.state)
        (WORK / "train_history.json").write_text(json.dumps(history, indent=1), encoding="utf-8")
    pool.close()
    print(f"best val selection score {best:.3f}; saved {args.out}")


if __name__ == "__main__":
    main()

