def explain(concept: str, language: str | None) -> str:
    table = _HELP[_lang(language)]
    return table.get(concept, table["text"])[0]


def where_to_find(concept: str, language: str | None) -> str | None:
    return _HELP[_lang(language)].get(concept, ("", ""))[1] or None


def documents(concepts, language: str | None) -> list[str]:
    """Names of the documents the user should keep ready, in form order, without repeats."""
    names = _DOCUMENTS[_lang(language)]
    keys = dict.fromkeys(_DOCUMENT_OF[c] for c in concepts if c in _DOCUMENT_OF)
    return [names[k] for k in keys]
