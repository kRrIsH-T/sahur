def is_consent(field) -> bool:
    """Whether this is a declaration the user must read and complete themselves."""
    is_checkbox = getattr(field, "control_type", "") == "CheckBox" or getattr(field, "kind", "") == "checkbox"
    return (is_checkbox and
            _CONSENT.search(f"{getattr(field, 'label', '')} {getattr(field, 'help', '')}".casefold()) is not None)


def classify(field) -> str:
    """The concept of a fields.Field (key, label, kind, protected...). Only the label and kind are used."""
    label = (getattr(field, "label", "") or "").casefold()
    kind = getattr(field, "kind", "text")
    if kind == "secret":
        return next((c for c in _SECRET_ORDER if _has(c, label)), "pin" if "pin" in label or "पिन" in label
                    else "card_number" if _has("card_number", label) else "secret")
    if kind in {"file", "manual"}:
        return kind
    if getattr(field, "protected", False):
        return "secret"
    if kind not in {"aadhaar", "pan"} and _has("card_number", label):
        return "card_number"
    if kind == "account" and _has("ckyc", label):
        return "ckyc"
    if kind in {"aadhaar", "pan", "ifsc", "postal", "mobile", "email", "date", "account"}:
        return kind
    if kind == "checkbox":
        if _has("captcha", label):
            return "captcha"  # reCAPTCHA's "I'm not a robot" is the person's to tick
        if is_consent(field):
            return "manual"  # a legal consent or declaration: read and ticked by the person themselves
        return "pep" if _has("pep", label) else "checkbox"
    for concept in _TEXT_ORDER:
        if _has(concept, label):
            # A choice list can be a place (state) or gender, but never a free-text name.
            if kind == "choice" and concept in {"name", "relative_name", "nominee", "address"}:
                continue
            return concept
    return "choice" if kind == "choice" else "text"


def sensitivity(concept: str) -> str:
    return _SENSITIVITY.get(concept, FILL)


